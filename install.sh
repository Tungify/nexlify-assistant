#!/usr/bin/env bash
# Registers the native-messaging host for the FB Assistant extension (macOS, Chrome stable).
# Run ONCE after loading the unpacked extension:
#     ./install.sh <extension-id>
# Re-run if you move this folder or switch to a different node/CLI.
set -euo pipefail

EXT_ID="${1:-}"
if [ -z "$EXT_ID" ]; then
  echo "Usage: ./install.sh <extension-id>"
  echo "  (copy the ID from chrome://extensions after Load unpacked)"
  exit 1
fi

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
HOST_JS="$DIR/native-host/host.js"
HOST_SH="$DIR/native-host/host.sh"

NODE_BIN="$(command -v node || true)"
[ -z "$NODE_BIN" ] && { echo "ERROR: node not found in PATH"; exit 1; }
CLAUDE_BIN="$(command -v claude || true)"
CODEX_BIN="$(command -v codex || command -v chatgpt || true)"

# GUI-launched processes on macOS get a minimal PATH, so Chrome won't find node
# or the CLIs by name. The wrapper below bakes in the dirs we discovered now.
EXTRA_PATH="$(dirname "$NODE_BIN")"
[ -n "$CLAUDE_BIN" ] && EXTRA_PATH="$EXTRA_PATH:$(dirname "$CLAUDE_BIN")"
[ -n "$CODEX_BIN" ]  && EXTRA_PATH="$EXTRA_PATH:$(dirname "$CODEX_BIN")"

cat > "$HOST_SH" <<EOF
#!/bin/bash
# Generated by install.sh — do not edit by hand; re-run install.sh instead.
export PATH="$EXTRA_PATH:/opt/homebrew/bin:/usr/local/bin:\$HOME/.local/bin:\$PATH"
export CLAUDE_BIN="$CLAUDE_BIN"
export CODEX_BIN="$CODEX_BIN"
# The node baked in at install time disappears when nvm upgrades it (Chrome then
# only says "Native host has exited"). Fall back to any node on PATH, then the
# newest nvm-installed one.
NODE="$NODE_BIN"
[ -x "\$NODE" ] || NODE="\$(command -v node || true)"
[ -n "\$NODE" ] && [ -x "\$NODE" ] || NODE="\$(ls -1d "\$HOME"/.nvm/versions/node/*/bin/node 2>/dev/null | sort -V | tail -1)"
exec "\$NODE" "$HOST_JS" "\$@"
EOF
chmod +x "$HOST_SH"

TARGET_DIR="$HOME/Library/Application Support/Google/Chrome/NativeMessagingHosts"
mkdir -p "$TARGET_DIR"
cat > "$TARGET_DIR/com.nexlify.assistant.json" <<EOF
{
  "name": "com.nexlify.assistant",
  "description": "Nexlify FB Assistant native host",
  "path": "$HOST_SH",
  "type": "stdio",
  "allowed_origins": [ "chrome-extension://$EXT_ID/" ]
}
EOF

echo "Installed native host manifest:"
echo "  $TARGET_DIR/com.nexlify.assistant.json"
echo "  node   = $NODE_BIN"
echo "  claude = ${CLAUDE_BIN:-<not found>}"
echo "  codex  = ${CODEX_BIN:-<not found>}"
echo
echo "Now FULLY quit and reopen Chrome, then click the extension icon."
